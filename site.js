function currentLanguage() {
  const query = new URLSearchParams(location.search).get("lang");
  const stored = localStorage.getItem("lang");
  const candidate = query || (stored === "ua" ? "uk" : stored) || "de";
  return translations[candidate] ? candidate : "de";
}

function setLanguage(language, updateUrl = true) {
  const lang = translations[language] ? language : "de";
  const t = translations[lang];
  document.documentElement.lang = lang;
  document.title = t.title;
  document.querySelector('meta[name="description"]').content = t.description;
  document.querySelector('meta[property="og:title"]').content = t.title;
  document.querySelector('meta[property="og:description"]').content =
    t.description;
  document.querySelectorAll("[data-i]").forEach((element) => {
    if (t[element.dataset.i]) element.textContent = t[element.dataset.i];
  });
  document.querySelector('[data-commercial="heroTitle"]').innerHTML =
    t.heroTitle;
  document.querySelector('[data-commercial="athleteNav"]').textContent =
    t.athleteNav;
  document.querySelector('[data-commercial="bookSession"]').textContent =
    t.book;
  document.querySelector('[data-commercial="stickyBook"]').textContent =
    t.stickyBook;
  document.getElementById("bookingTitle").textContent = t.bookingTitle;
  document
    .querySelector(".booking-close")
    .setAttribute("aria-label", t.closeBooking);
  document.querySelector('[data-commercial="athleteButton"]').textContent =
    t.athleteButton;
  document.querySelector('[data-commercial="quickLocation"]').textContent =
    t.location;
  document.querySelector('[data-commercial="careerTeaser"]').textContent =
    t.careerTeaser;
  document.querySelector('[data-commercial="careerLink"]').textContent =
    t.careerLink;
  document.getElementById("winTitle").textContent = t.winTitle;
  document.getElementById("winText").textContent = t.winText;
  document.getElementById("winNote").textContent = t.winNote;
  document.getElementById("winLink").textContent = t.winLink;
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const isActive = button.dataset.lang === lang;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
  const canonicalUrl =
    lang === "de"
      ? "https://www.olga-liakhova.com/"
      : `https://www.olga-liakhova.com/?lang=${lang}`;
  document.querySelector('link[rel="canonical"]').href = canonicalUrl;
  document.querySelector('meta[property="og:url"]').content = canonicalUrl;

  document.getElementById("serviceGrid").innerHTML = services[lang]
    .map(
      (service, index) => `
    <article class="card">
      <div class="n">${String(index + 1).padStart(2, "0")}</div>
      <h3>${service[0]}</h3><p>${service[1]}</p>
      <div class="price"><span>${t.price}</span><b>${service[2]}</b></div>
      <div class="card-actions"><a class="btn gold" href="${service[4]}" target="_blank" rel="noopener">${service[3]}</a>${service[5] ? `<a class="text-link" href="${service[5]}">${t.learnMore} →</a>` : ""}</div>
    </article>`,
    )
    .join("");

  document.getElementById("bookingOptions").innerHTML = services[lang]
    .map(
      (service) => `
      <a class="booking-option" href="${service[4]}">
        <span><strong>${service[0]}</strong><span class="booking-option-price">${service[2].replace(/<br>/g, " · ")}</span></span>
        <b aria-hidden="true">→</b>
      </a>`,
    )
    .join("");

  document.getElementById("faqList").innerHTML = faqs[lang]
    .map(
      ([question, answer]) =>
        `<details><summary>${question}</summary><p>${answer}</p></details>`,
    )
    .join("");

  localStorage.setItem("lang", lang);
  if (updateUrl) {
    const url = new URL(location.href);
    if (lang === "de") url.searchParams.delete("lang");
    else url.searchParams.set("lang", lang);
    history.replaceState({}, "", url);
  }
}

document
  .querySelectorAll("[data-lang]")
  .forEach((button) =>
    button.addEventListener("click", () => setLanguage(button.dataset.lang)),
  );
setLanguage(currentLanguage(), false);

const bookingButton = document.querySelector('[data-commercial="stickyBook"]');
const bookingPicker = document.getElementById("bookingPicker");
const bookingPanel = bookingPicker.querySelector(".booking-panel");
const bookingClose = bookingPicker.querySelector(".booking-close");

function openBookingPicker() {
  bookingPicker.hidden = false;
  bookingButton.setAttribute("aria-expanded", "true");
  document.body.style.overflow = "hidden";
  bookingClose.focus();
}

function closeBookingPicker() {
  bookingPicker.hidden = true;
  bookingButton.setAttribute("aria-expanded", "false");
  document.body.style.overflow = "";
  bookingButton.focus();
}

bookingButton.addEventListener("click", openBookingPicker);
bookingClose.addEventListener("click", closeBookingPicker);
bookingPicker.addEventListener("click", (event) => {
  if (!bookingPanel.contains(event.target)) closeBookingPicker();
});
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && !bookingPicker.hidden) closeBookingPicker();
});
